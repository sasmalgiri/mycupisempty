/**
 * Get translation — returns Bengali if lang is 'bn', otherwise returns the key
 * Usage: t('nav.dashboard', 'bn') → 'ড্যাশবোর্ড'
 */
export function t(key: string, lang: string = 'en'): string {
  if (lang === 'bn' && bn[key]) return bn[key];
  return key;
}

/**
 * Get user language from board code
 * WBBSE students default to Bengali
 */
export function getLangFromBoard(boardCode: string): string {
  if (boardCode === 'wb_board') return 'bn';
  return 'en';
}
